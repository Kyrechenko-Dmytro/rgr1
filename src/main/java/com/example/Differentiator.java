package com.example;

/**
 * Інтерфейс для обчислення похідної функції.
 * Дозволяє підставляти різні методи диференціювання (центральний, лівий, правий і т.д.)
 * без зміни коду, що використовує диференціатор — принцип відкритості/закритості (OCP).
 */
public interface Differentiator {
    /**
     * Обчислює наближене значення похідної функції f у точці x.
     *
     * @param f функція
     * @param x точка диференціювання
     * @return f'(x)
     */
    double differentiate(Function f, double x);
}
