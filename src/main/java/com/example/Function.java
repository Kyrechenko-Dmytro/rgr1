package com.example;

/**
 * Інтерфейс, що представляє математичну функцію однієї змінної типу double.
 * Будь-яка аналітична або таблична функція реалізує цей інтерфейс.
 */
public interface Function {

    /**
     * Обчислює значення функції в точці x.
     *
     * @param x значення аргументу типу double
     * @return значення функції f(x)
     */
    double evaluate(double x);

    /**
     * Повертає назву функції (для виведення у файл/консоль).
     *
     * @return рядок з назвою або описом функції
     */
    String getName();
}
